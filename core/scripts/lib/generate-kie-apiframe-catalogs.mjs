const scriptsDir = dirname(fileURLToPath(import.meta.url));
export const defaultWhitelistPath = resolve(scriptsDir, '../provider-model-whitelist.json');

export function loadProviderModelWhitelist(whitelistPath = defaultWhitelistPath) {
  return JSON.parse(readFileSync(whitelistPath, 'utf8'));
}

function assertWhitelistCoverage(providerName, whitelistEntries, catalogByLocator) {
  const missing = whitelistEntries
    .map(entry => entry.locator)
    .filter(locator => !catalogByLocator.has(locator));
  if (missing.length) {
    throw new Error(
      `Whitelist ${providerName} entries missing from snapshots: ${missing.join(', ')}`,
    );
  }
}

async function writeDescribeArtifacts(outputDir, describeEntries, registryTsConfig = null) {
  await mkdir(outputDir, { recursive: true });

  const keepFiles = new Set(['registry.json', 'registry.ts']);
  for (const entry of describeEntries) {
    keepFiles.add(`${sanitizeFileName(entry.locator)}.json`);
  }

  const existingFiles = await readdir(outputDir);
  for (const fileName of existingFiles) {
    if (keepFiles.has(fileName)) continue;
    if (!fileName.endsWith('.json') && !fileName.endsWith('.ts')) continue;
    await unlink(join(outputDir, fileName));
  }

  const registry = describeEntries.map(entry => ({
    locator: entry.locator,
    modelId: entry.modelId,
    label: entry.label,
    outputType: entry.outputType,
    file: `${sanitizeFileName(entry.locator)}.json`,
  }));

  for (const entry of describeEntries) {
    const fileName = `${sanitizeFileName(entry.locator)}.json`;
    await writeJsonAtomically(join(outputDir, fileName), entry);
  }
  await writeJsonAtomically(join(outputDir, 'registry.json'), registry);

  if (registryTsConfig) {
    const registryTsSource = renderDescribeRegistryTs({ entries: describeEntries, ...registryTsConfig });
    // Overwrite unconditionally (even a hand-edited file) - this is the
    // whole point: registry.ts must always reflect the actual entries.
    await writeFile(join(outputDir, 'registry.ts'), registryTsSource, 'utf8');
  }

  return registry;
}

export { writeDescribeArtifacts };

function sanitizeFileName(locator) {
  return locator.replace(/^[^:]+:\/\//, '').replace(/\//g, '__');
}

// Deterministically derives a camelCase import identifier from a describe
// JSON file name, e.g. `market__seedream__5-pro-text-to-image.json` ->
// `marketSeedream5ProTextToImage`. Dots are dropped rather than treated as
// word boundaries so `gpt-image-1.5.json` -> `gptImage15` (matches the
// previous hand-written convention).
function toImportIdentifier(fileName) {
  const base = fileName.replace(/\.json$/, '');
  const words = base.split(/[_-]+/).filter(Boolean).map(word => word.replace(/\./g, '')).filter(Boolean);
  return words
    .map((word, index) => (index === 0
      ? word.charAt(0).toLowerCase() + word.slice(1)
      : word.charAt(0).toUpperCase() + word.slice(1)))
    .join('');
}

/**
 * Renders a fully self-contained `registry.ts` module for a describe
 * directory: one static import per describe JSON file (required for
 * bundlers to include the JSON at build time) plus lookup helpers. This is
 * always derived from the actual entries passed in, so it can never drift
 * from the JSON files on disk / the whitelist that produced them - the file
 * is regenerated (overwritten) on every run.
 */
function renderDescribeRegistryTs({ entries, typeName, typeBody, getFnName, listFnName }) {
  const sorted = [...entries].sort((left, right) => left.locator.localeCompare(right.locator));
  const imports = sorted.map(entry => {
    const fileName = `${sanitizeFileName(entry.locator)}.json`;
    return { identifier: toImportIdentifier(fileName), fileName };
  });

  const importLines = imports.map(({ identifier, fileName }) => `import ${identifier} from './${fileName}';`);
  const entryLines = imports.map(({ identifier }) => `  ${identifier},`);

  return `// AUTO-GENERATED by generate-kie-apiframe-catalogs.mjs. Do not hand-edit:
// this file is overwritten on every regeneration to stay in sync with the
// describe JSON files in this directory and the provider whitelist.
${importLines.join('\n')}

${typeBody.trim()}

const DESCRIBE_ENTRIES: ${typeName}[] = [
${entryLines.join('\n')}
] as ${typeName}[];

const describeByLocator = new Map(
  DESCRIBE_ENTRIES.map(entry => [entry.locator, entry]),
);

export function ${getFnName}(locator: string): ${typeName} | undefined {
  return describeByLocator.get(locator);
}

export function ${listFnName}(): string[] {
  return [...describeByLocator.keys()].sort((left, right) => left.localeCompare(right));
}
`;
}

const KIE_DESCRIBE_ENTRY_TYPE_BODY = `export type KieDescribeEntry = {
  locator: string;
  modelId: string;
  providerId: 'kie';
  outputType: string;
  label: string;
  endpoint: {
    method: string;
    path: string;
  };
  requestSchema: Record<string, unknown>;
  wireMetadata: {
    modelField: string;
    inputField: string;
    callbackField: string;
  };
};`;

const APIFRAME_DESCRIBE_ENTRY_TYPE_BODY = `export type ApiframeDescribeEntry = {
  locator: string;
  modelId: string;
  providerId: 'apiframe';
  modality: string;
  label: string;
  outputType: string;
  endpoint: {
    method: string;
    path: string;
  };
  requestSchema: Record<string, unknown>;
  wireMetadata: {
    modelField: string;
    paramsField: string | null;
    wirePath: string | null;
  };
};`;

export async function generateKieApiframeCatalogs({
  kieDescribeRoot,
  apiframeOpenApiPath,
  whitelist,
  kieCatalogOutputPath,
  apiframeCatalogOutputPath,
  kieDescribeOutputDir,
  apiframeDescribeOutputDir,
  apiframeModelsSummaryPath = null,
  mutateWhitelist = null,
}) {
  const effectiveWhitelist = structuredClone(whitelist);
  mutateWhitelist?.(effectiveWhitelist);

  const kieCatalogResult = await buildKieCatalogEntries(kieDescribeRoot, { collectDiagnostics: true });
  const kieCatalog = kieCatalogResult.entries;
  for (const diagnostic of kieCatalogResult.diagnostics) {
    console.warn(`[kie-catalog] ${diagnostic.message}`);
  }
  const openapi = await readJsonFile(apiframeOpenApiPath);
  let modelsSummary = null;
  if (apiframeModelsSummaryPath) {
    try {
      modelsSummary = await readJsonFile(apiframeModelsSummaryPath);
    } catch {
      modelsSummary = null;
    }
  }
  const apiframeCatalog = buildApiframeCatalogEntries(openapi, modelsSummary);

  const kieByLocator = new Map(kieCatalog.map(entry => [entry.locator, entry]));
  const apiframeByLocator = new Map(apiframeCatalog.map(entry => [entry.locator, entry]));

  assertWhitelistCoverage('kie', effectiveWhitelist.kie, kieByLocator);
  assertWhitelistCoverage('apiframe', effectiveWhitelist.apiframe, apiframeByLocator);

  const kieDescribe = await buildKieDescribeEntries(kieDescribeRoot, effectiveWhitelist.kie);
  const apiframeDescribe = buildApiframeDescribeEntries(
    openapi,
    effectiveWhitelist.apiframe,
    modelsSummary,
  );

  if (kieDescribe.length !== effectiveWhitelist.kie.length) {
    throw new Error('Failed to build all Kie whitelist describe entries');
  }
  if (apiframeDescribe.length !== effectiveWhitelist.apiframe.length) {
    throw new Error('Failed to build all Apiframe whitelist describe entries');
  }

  const whitelistKieLocators = new Set(effectiveWhitelist.kie.map(entry => entry.locator));
  const whitelistApiframeLocators = new Set(effectiveWhitelist.apiframe.map(entry => entry.locator));
  const publicKieCatalog = kieCatalog.map(entry => ({
    ...stripInternalFields(entry),
    supported: whitelistKieLocators.has(entry.locator),
  }));
  const publicApiframeCatalog = apiframeCatalog.map(entry => ({
    ...stripInternalFields(entry),
    supported: whitelistApiframeLocators.has(entry.locator),
  }));

  await writeJsonAtomically(kieCatalogOutputPath, publicKieCatalog);
  await writeJsonAtomically(apiframeCatalogOutputPath, publicApiframeCatalog);
  await writeDescribeArtifacts(kieDescribeOutputDir, kieDescribe, {
    typeName: 'KieDescribeEntry',
    typeBody: KIE_DESCRIBE_ENTRY_TYPE_BODY,
    getFnName: 'getKieDescribeEntry',
    listFnName: 'listKieDescribeLocators',
  });
  await writeDescribeArtifacts(apiframeDescribeOutputDir, apiframeDescribe, {
    typeName: 'ApiframeDescribeEntry',
    typeBody: APIFRAME_DESCRIBE_ENTRY_TYPE_BODY,
    getFnName: 'getApiframeDescribeEntry',
    listFnName: 'listApiframeDescribeLocators',
  });

  return {
    kieCatalog: publicKieCatalog,
    apiframeCatalog: publicApiframeCatalog,
    kieDescribe,
    apiframeDescribe,
    diagnostics: kieCatalogResult.diagnostics,
  };
}

function stripInternalFields(entry) {
  const { sourcePath: _sourcePath, modelId: _modelId, modality: _modality, ...publicEntry } = entry;
  return publicEntry;
}

export { buildApiframeCatalogEntries, buildKieCatalogEntries };
