import { generateKieApiframeCatalogs } from './generate-kie-apiframe-catalogs.mjs';
import { generateReplicateCatalog } from './generate-replicate-catalog.mjs';
import { generateRunningHubCatalog } from './generate-runninghub-catalog.mjs';

export const DEFAULT_PROVIDERS = ['runninghub', 'replicate', 'kie', 'apiframe'];

function errorMessage(error) {
  return error instanceof Error ? error.message : String(error);
}

/**
 * Runs every requested provider's offline catalog generation independently:
 * one provider failing (missing/malformed local snapshot, whitelist
 * coverage gap, etc.) never prevents the others from generating, and never
 * touches that provider's previous output artifacts (each generator
 * validates its input before writing anything). Reads only local
 * `catalog-data`/`describe-data` snapshots passed in via options - never the
 * network.
 *
 * Kie and Apiframe are generated by a single shared call (their offline
 * generator always produces both together from the same whitelist file),
 * so requesting either one reports a result for both.
 */
export async function generateProviderCatalogs(options = {}) {
  const { runninghub, replicate, kieApiframe, providers = DEFAULT_PROVIDERS } = options;
  const wanted = new Set(providers);
  const results = [];

  if (wanted.has('runninghub')) {
    try {
      const detail = await generateRunningHubCatalog(runninghub);
      results.push({ provider: 'runninghub', status: 'success', error: null, detail });
    } catch (error) {
      results.push({ provider: 'runninghub', status: 'failed', error: errorMessage(error), detail: null });
    }
  }

  if (wanted.has('replicate')) {
    try {
      const detail = await generateReplicateCatalog(replicate);
      results.push({ provider: 'replicate', status: 'success', error: null, detail });
    } catch (error) {
      results.push({ provider: 'replicate', status: 'failed', error: errorMessage(error), detail: null });
    }
  }

  if (wanted.has('kie') || wanted.has('apiframe')) {
    try {
      const detail = await generateKieApiframeCatalogs(kieApiframe);
      if (wanted.has('kie')) {
        results.push({
          provider: 'kie',
          status: 'success',
          error: null,
          detail: { catalog: detail.kieCatalog, describe: detail.kieDescribe },
        });
      }
      if (wanted.has('apiframe')) {
        results.push({
          provider: 'apiframe',
          status: 'success',
          error: null,
          detail: { catalog: detail.apiframeCatalog, describe: detail.apiframeDescribe },
        });
      }
    } catch (error) {
      const message = errorMessage(error);
      if (wanted.has('kie')) results.push({ provider: 'kie', status: 'failed', error: message, detail: null });
      if (wanted.has('apiframe')) results.push({ provider: 'apiframe', status: 'failed', error: message, detail: null });
    }
  }

  return { results, success: results.every(result => result.status === 'success') };
}

function detailCount(result) {
  if (!result.detail) return null;
  if (Array.isArray(result.detail.registry)) return result.detail.registry.length;
  if (Array.isArray(result.detail)) return result.detail.length;
  if (Array.isArray(result.detail.catalog)) return result.detail.catalog.length;
  return null;
}

export function formatGenerateCatalogsSummary(summary) {
  const lines = summary.results.map(result => {
    if (result.status !== 'success') {
      return `[generate-provider-catalogs] ${result.provider}: FAILED - ${result.error}`;
    }
    const count = detailCount(result);
    return `[generate-provider-catalogs] ${result.provider}: OK${count === null ? '' : ` (${count} models)`}`;
  });
  lines.push(
    summary.success
      ? '[generate-provider-catalogs] all providers generated successfully'
      : '[generate-provider-catalogs] one or more providers failed; their previous generated artifacts were preserved',
  );
  return lines.join('\n');
}

export async function runGenerateProviderCatalogsCli(options = {}) {
  const { log = console.log, ...generateOptions } = options;
  const summary = await generateProviderCatalogs(generateOptions);
  log(formatGenerateCatalogsSummary(summary));
  return summary.success ? 0 : 1;
}
